/// Draw an octant codepoint onto the canvas.
///
/// Every `U+1CD00..=U+1CDE5` codepoint maps to an 8-bit bitmask via
/// [`OCTANT_MASKS`]; each set bit fills one sub-cell of the 2×4 grid.
pub(super) fn draw(canvas: &mut Canvas, ch: char) {
    let idx = (ch as u32 - OCTANT_START as u32) as usize;
    let bits = OCTANT_MASKS[idx];

    let w = canvas.width() as f32;
    let h = canvas.height() as f32;
    let hw = (w / 2.0).round();
    let q1 = (h / 4.0).round();
    let q2 = (h * 2.0 / 4.0).round();
    let q3 = (h * 3.0 / 4.0).round();

    if bits & 0x01 != 0 {
        canvas.fill_rect(RectF::new(0.0, 0.0, hw, q1), 255);
    }
    if bits & 0x02 != 0 {
        canvas.fill_rect(RectF::new(hw, 0.0, w - hw, q1), 255);
    }
    if bits & 0x04 != 0 {
        canvas.fill_rect(RectF::new(0.0, q1, hw, q2 - q1), 255);
    }
    if bits & 0x08 != 0 {
        canvas.fill_rect(RectF::new(hw, q1, w - hw, q2 - q1), 255);
    }
    if bits & 0x10 != 0 {
        canvas.fill_rect(RectF::new(0.0, q2, hw, q3 - q2), 255);
    }
    if bits & 0x20 != 0 {
        canvas.fill_rect(RectF::new(hw, q2, w - hw, q3 - q2), 255);
    }
    if bits & 0x40 != 0 {
        canvas.fill_rect(RectF::new(0.0, q3, hw, h - q3), 255);
    }
    if bits & 0x80 != 0 {
        canvas.fill_rect(RectF::new(hw, q3, w - hw, h - q3), 255);
    }
}
