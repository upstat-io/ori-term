//! Octant subcell glyphs (U+1CD00–U+1CDE5).
//!
//! 2×4 sub-cell grid per terminal cell, 8-bit bitmask per codepoint.
//! Bit order is row-major `0..7` per the canonical artifact at
//! `plans/spec-conformance/specs/octant-bitmask-mapping.md`
//! (cross-checked against `WezTerm` `customglyph.rs:317-560` and
//! `Kitty` `decorations.c:979-1026` — 0 discrepancies after normalizing
//! Kitty's column-major encoding).
//!
//! ```text
//! +-----+-----+
//! | b0 | b1 | row 0 (top)
//! +-----+-----+
//! | b2 | b3 | row 1 (upper-mid)
//! +-----+-----+
//! | b4 | b5 | row 2 (lower-mid)
//! +-----+-----+
//! | b6 | b7 | row 3 (bottom)
//! +-----+-----+
//! ```
//!
//! `0x00` (empty) and `0xFF` (full) are not encoded in this range —
//! `U+0020` SPACE and `U+2588` FULL BLOCK cover them. 24 other masks
//! are skipped because they match pre-existing half-block / sextant
//! glyphs in `U+2580..=U+259F` and `U+1FB00..=U+1FB3B`.

use super::{Canvas, RectF};

/// First octant codepoint (inclusive).
pub(super) const OCTANT_START: char = '\u{1CD00}';
/// Last octant codepoint (inclusive).
pub(super) const OCTANT_END: char = '\u{1CDE5}';

/// Canonical octant codepoint→bitmask table indexed by `ch - OCTANT_START`.
